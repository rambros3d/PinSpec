import {
  formatMuxLabel,
  getChipMuxModel,
  getChipVendor,
  type ChipData,
  type PinInfo,
  type WorkspaceState,
} from '../types';

/** Net-name macro prefix, e.g. "imu_clk" -> "IMU_CLK". */
function toUpperSnakeCase(input: string): string {
  const cleaned = input
    .trim()
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/([a-z])([A-Z])/g, '$1_$2')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase();
  if (!cleaned) return 'PIN';
  return /^[0-9]/.test(cleaned) ? `P_${cleaned}` : cleaned;
}

/** STM32/CH32 port and pin number: "PA5" -> { GPIOA, 5 }, "PA1 / PD6" -> { GPIOA, 1 }. */
function parsePortAndPin(pinName: string): { port: string; pinNum: number } | null {
  const match = pinName.match(/^P([A-K])([0-9]{1,2})/);
  if (!match) return null;
  return {
    port: `GPIO${match[1]}`,
    pinNum: Number.parseInt(match[2], 10),
  };
}

/** RP GPIO number: "GPIO12" -> 12. */
function parseGpionum(pinName: string): number | null {
  const match = pinName.match(/^GPIO(\d+)/i);
  return match ? Number.parseInt(match[1], 10) : null;
}

/** Pico SDK pin function enum name for a peripheral. */
function picoFuncName(peripheral: string): string {
  if (/^SPI/i.test(peripheral)) return 'GPIO_FUNC_SPI';
  if (/^UART/i.test(peripheral)) return 'GPIO_FUNC_UART';
  if (/^I2C/i.test(peripheral)) return 'GPIO_FUNC_I2C';
  if (/^PWM/i.test(peripheral)) return 'GPIO_FUNC_PWM';
  if (/^HSTX/i.test(peripheral)) return 'GPIO_FUNC_HSTX';
  if (/^USB/i.test(peripheral)) return 'GPIO_FUNC_USB';
  if (/^XIP/i.test(peripheral)) return 'GPIO_FUNC_XIP';
  const pio = peripheral.match(/^PIO(\d+)/i);
  if (pio) return `GPIO_FUNC_PIO${pio[1]}`;
  return 'GPIO_FUNC_NULL';
}

/** Split a PWM slice/channel resource key such as "PWM3B" into slice 3, channel 1. */
function parsePwmResource(resourceId: string | undefined, signal: string): { slice: number; channel: 0 | 1 } | null {
  const match = (resourceId ?? signal).match(/^PWM(\d+)([AB])$/);
  if (!match) return null;
  return { slice: Number.parseInt(match[1], 10), channel: match[2] === 'A' ? 0 : 1 };
}

function headerPreamble(chip: ChipData, guard: string): string[] {
  return [
    `/* Generated by PinCraft for ${chip.id} (${chip.package.name}) */`,
    `#ifndef ${guard}`,
    `#define ${guard}`,
    ``,
    `#define PINCRAFT_MCU_ID "${chip.id}"`,
    `#define PINCRAFT_PACKAGE "${chip.package.name}"`,
    ``,
  ];
}

function emptyHeader(chip: ChipData, guard: string): string {
  const lines = [...headerPreamble(chip, guard), `/* No pins assigned yet. */`, ``];
  lines.push(`#endif /* ${guard} */`);
  return lines.join('\n') + '\n';
}

/** Iterate assigned pins in deterministic physical-position order. */
function sortedAssignments(state: WorkspaceState): string[] {
  return Object.keys(state.assignments).sort((a, b) =>
    a.localeCompare(b, undefined, { numeric: true }),
  );
}

/** STM32 header: unchanged `_GPIO_PORT` / `_PIN` / `_AF` macro contract. */
function formatStm32(chip: ChipData, state: WorkspaceState, guard: string): string {
  const pinMap = new Map<string, PinInfo>(chip.pins.map((p) => [p.pos, p]));
  const positions = sortedAssignments(state);
  if (positions.length === 0) return emptyHeader(chip, guard);

  const lines = headerPreamble(chip, guard);
  const muxModel = getChipMuxModel(chip);
  const usedMacros = new Map<string, number>();

  for (const pos of positions) {
    const asgn = state.assignments[pos];
    const pin = pinMap.get(pos);
    if (!pin) continue;

    const rawLabel = state.labels[pos]?.trim();
    const baseMacro = rawLabel
      ? toUpperSnakeCase(rawLabel)
      : toUpperSnakeCase(`${asgn.peripheral}_${asgn.signal}`);
    const count = usedMacros.get(baseMacro) ?? 0;
    usedMacros.set(baseMacro, count + 1);
    const macro = count === 0 ? baseMacro : `${baseMacro}_${count + 1}`;

    const portPin = parsePortAndPin(pin.name);
    const muxLabel = formatMuxLabel(asgn, muxModel);
    lines.push(`/* Pin ${pos}: ${pin.name} -> ${asgn.peripheral}_${asgn.signal} [${muxLabel}] */`);
    if (portPin) {
      lines.push(`#define ${macro}_GPIO_PORT ${portPin.port}`);
      lines.push(`#define ${macro}_PIN ${portPin.pinNum}U`);
    } else {
      lines.push(`#define ${macro}_GPIO_PORT NULL`);
      lines.push(`#define ${macro}_PIN 0U`);
    }
    if (asgn.af !== null) {
      lines.push(`#define ${macro}_AF ${asgn.af}U`);
    } else {
      lines.push(`#define ${macro}_AF 0xFFU /* None / AFIO */`);
    }
    lines.push(``);
  }

  lines.push(`#endif /* ${guard} */`);
  return lines.join('\n') + '\n';
}

/** RP header: Pico SDK `GPIO_FUNC_*` plus PWM slice/channel and PIO macros. */
function formatRp(chip: ChipData, state: WorkspaceState, guard: string): string {
  const pinMap = new Map<string, PinInfo>(chip.pins.map((p) => [p.pos, p]));
  const positions = sortedAssignments(state);
  if (positions.length === 0) return emptyHeader(chip, guard);

  const lines = [
    ...headerPreamble(chip, guard),
    `/* Pico SDK pin functions: GPIO_FUNC_* (FUNCSEL values) */`,
    ``,
  ];
  const muxModel = getChipMuxModel(chip);
  const usedMacros = new Map<string, number>();

  for (const pos of positions) {
    const asgn = state.assignments[pos];
    const pin = pinMap.get(pos);
    if (!pin) continue;

    const rawLabel = state.labels[pos]?.trim();
    const baseMacro = rawLabel
      ? toUpperSnakeCase(rawLabel)
      : toUpperSnakeCase(`${asgn.peripheral}_${asgn.signal}`);
    const count = usedMacros.get(baseMacro) ?? 0;
    usedMacros.set(baseMacro, count + 1);
    const macro = count === 0 ? baseMacro : `${baseMacro}_${count + 1}`;

    const gpionum = parseGpionum(pin.name);
    const muxLabel = formatMuxLabel(asgn, muxModel);
    lines.push(`/* Pin ${pos}: ${pin.name} -> ${asgn.peripheral}_${asgn.signal} [${muxLabel}] */`);
    lines.push(`#define ${macro}_GPIO ${gpionum === null ? 0 : gpionum}U`);
    lines.push(`#define ${macro}_GPIO_FUNC ${picoFuncName(asgn.peripheral)}`);

    const pwm = parsePwmResource(asgn.resourceId, asgn.signal);
    if (pwm) {
      lines.push(`#define ${macro}_PWM_SLICE ${pwm.slice}U`);
      lines.push(`#define ${macro}_PWM_CHANNEL ${pwm.channel}U`);
    }

    const pio = state.pioAssignments?.[pos];
    if (pio) {
      lines.push(`#define ${macro}_PIO_INSTANCE ${pio.instance}`);
      lines.push(`#define ${macro}_PIO_SM ${pio.sm ?? 0}U`);
      if (pio.role) lines.push(`#define ${macro}_PIO_ROLE "${pio.role}"`);
    }
    lines.push(``);
  }

  lines.push(`#endif /* ${guard} */`);
  return lines.join('\n') + '\n';
}

/** CH32 header: ch32v003fun port/pin macros plus an active remap summary. */
function formatCh32(chip: ChipData, state: WorkspaceState, guard: string): string {
  const pinMap = new Map<string, PinInfo>(chip.pins.map((p) => [p.pos, p]));
  const positions = sortedAssignments(state);
  if (positions.length === 0) return emptyHeader(chip, guard);

  const lines = [
    ...headerPreamble(chip, guard),
    `/* ch32v003fun / WCH SDK port and pin mapping */`,
    ``,
  ];
  const muxModel = getChipMuxModel(chip);
  const usedMacros = new Map<string, number>();

  for (const pos of positions) {
    const asgn = state.assignments[pos];
    const pin = pinMap.get(pos);
    if (!pin) continue;

    const rawLabel = state.labels[pos]?.trim();
    const baseMacro = rawLabel
      ? toUpperSnakeCase(rawLabel)
      : toUpperSnakeCase(`${asgn.peripheral}_${asgn.signal}`);
    const count = usedMacros.get(baseMacro) ?? 0;
    usedMacros.set(baseMacro, count + 1);
    const macro = count === 0 ? baseMacro : `${baseMacro}_${count + 1}`;

    const portPin = parsePortAndPin(pin.name);
    const muxLabel = formatMuxLabel(asgn, muxModel);
    lines.push(`/* Pin ${pos}: ${pin.name} -> ${asgn.peripheral}_${asgn.signal} [${muxLabel}] */`);
    lines.push(`#define ${macro}_PORT ${portPin?.port ?? 'NULL'}`);
    lines.push(`#define ${macro}_PIN ${portPin?.pinNum ?? 0}U`);
    const remapId = asgn.remapId ?? (asgn.af !== null ? asgn.af : undefined);
    lines.push(`#define ${macro}_RM ${remapId === undefined ? 0 : remapId}U`);
    lines.push(``);
  }

  lines.push(`/* Active remap groups (ch32v003fun):`);
  const remaps = Object.entries(state.activeRemaps ?? {}).sort(([a], [b]) => a.localeCompare(b));
  if (remaps.length === 0) {
    lines.push(` * none`);
  } else {
    for (const [peripheral, remapId] of remaps) {
      const option = chip.peripherals[peripheral]?.remaps?.find((r) => r.id === remapId);
      const name = option ? option.name : `RM${remapId}`;
      const note = option?.registerNote ? ` -- ${option.registerNote}` : '';
      lines.push(` * ${peripheral}: ${name}${note}`);
    }
  }
  lines.push(` */`);
  lines.push(``);
  lines.push(`#endif /* ${guard} */`);
  return lines.join('\n') + '\n';
}

/**
 * Generate a guarded C pinout header for the chip's vendor.
 * All mux comments come from `formatMuxLabel`, so non-AF mux models never
 * emit an `_AF` macro.
 */
export function exportCHeader(chip: ChipData, state: WorkspaceState): string {
  const guard = `PINCRAFT_${toUpperSnakeCase(chip.id)}_PINOUT_H`;
  switch (getChipVendor(chip)) {
    case 'rp':
      return formatRp(chip, state, guard);
    case 'ch32':
      return formatCh32(chip, state, guard);
    default:
      return formatStm32(chip, state, guard);
  }
}
