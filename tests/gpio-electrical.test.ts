import { deflateSync, inflateSync, strFromU8, strToU8 } from 'fflate';
import { describe, expect, it, vi } from 'vitest';
import { exportCHeader } from '../src/core/exporters/c-header';
import { exportCsv } from '../src/core/exporters/csv';
import { exportEmbassyRust } from '../src/core/exporters/embassy-rust';
import { exportPinoutJson, parsePinoutJson } from '../src/core/exporters/json';
import { cloneWorkspaceState, createWorkspaceHistory, statesEqual } from '../src/core/history';
import type { ChipData, GpioConfig, WorkspaceState } from '../src/core/types';
import { decodeWorkspaceState, encodeWorkspaceState } from '../src/core/url-state';

const chip: ChipData = {
  id: 'STM32G431CBU6',
  family: 'STM32G4',
  core: 'Cortex-M4',
  flashKb: 128,
  ramKb: 32,
  package: { name: 'UFQFPN48', kind: 'perimeter', pinCount: 4, sides: [1, 1, 1, 1] },
  pins: [
    { pos: '15', name: 'PA5', type: 'io', signals: [{ peripheral: 'SPI1', signal: 'SCK', af: 5 }] },
    { pos: '1', name: 'VBAT', type: 'power', signals: [] },
  ],
  peripherals: { SPI1: { kind: 'spi', signals: ['SCK'] } },
};

const baseState: WorkspaceState = {
  mcuId: chip.id,
  assignments: { '15': { peripheral: 'SPI1', signal: 'SCK', af: 5 } },
  labels: {},
  locked: {},
  peripheralModes: {},
};

const config: GpioConfig = {
  outputLevel: 'High',
  drive: 'OpenDrain',
  pull: 'Down',
  speed: 'VeryHigh',
};

const configuredState: WorkspaceState = {
  ...baseState,
  gpioConfig: { '15': config },
};

/** Baseline text recorded before electrical settings were introduced. */
const BASELINE_RUST =
  '// Generated by PinCraft for STM32G431CBU6 (UFQFPN48)\n' +
  '// Core: Cortex-M4 | Flash: 128 KB | RAM: 32 KB\n' +
  'use embassy_stm32::peripherals;\n' +
  '\n' +
  'pub struct BoardPins {\n' +
  '    // SPI1\n' +
  '    pub spi1_sck: peripherals::PA5, // Pin 15 (PA5) -> SPI1_SCK [AF5]\n' +
  '}\n' +
  '\n' +
  'impl BoardPins {\n' +
  '    pub fn from_peripherals(p: embassy_stm32::Peripherals) -> Self {\n' +
  '        Self {\n' +
  '            spi1_sck: p.PA5,\n' +
  '        }\n' +
  '    }\n' +
  '}\n';

const BASELINE_C =
  '/* Generated by PinCraft for STM32G431CBU6 (UFQFPN48) */\n' +
  '#ifndef PINCRAFT_STM32G431CBU6_PINOUT_H\n' +
  '#define PINCRAFT_STM32G431CBU6_PINOUT_H\n' +
  '\n' +
  '#define PINCRAFT_MCU_ID "STM32G431CBU6"\n' +
  '#define PINCRAFT_PACKAGE "UFQFPN48"\n' +
  '\n' +
  '/* Pin 15: PA5 -> SPI1_SCK [AF5] */\n' +
  '#define SPI1_SCK_GPIO_PORT GPIOA\n' +
  '#define SPI1_SCK_PIN 5U\n' +
  '#define SPI1_SCK_AF 5U\n' +
  '\n' +
  '#endif /* PINCRAFT_STM32G431CBU6_PINOUT_H */\n';

function decodeRawPayload(encoded: string): Record<string, unknown> {
  const bytes = Buffer.from(encoded.replace(/-/g, '+').replace(/_/g, '/'), 'base64');
  return JSON.parse(strFromU8(inflateSync(new Uint8Array(bytes)))) as Record<string, unknown>;
}

describe('GPIO electrical state model', () => {
  it('clones and compares settings', () => {
    const cloned = cloneWorkspaceState(configuredState);
    expect(cloned.gpioConfig).toEqual(configuredState.gpioConfig);
    expect(cloned.gpioConfig).not.toBe(configuredState.gpioConfig);
    expect(statesEqual(configuredState, cloned)).toBe(true);
    expect(statesEqual(configuredState, baseState)).toBe(false);
    expect(
      statesEqual(configuredState, {
        ...configuredState,
        gpioConfig: { '15': { ...config, speed: 'High' } },
      }),
    ).toBe(false);
  });

  it('undoes and redoes an electrical change', () => {
    const history = createWorkspaceHistory(baseState);
    expect(history.push(configuredState)).toBe(true);
    expect(history.current.gpioConfig).toEqual(configuredState.gpioConfig);
    expect(history.undo()?.gpioConfig).toBeUndefined();
    expect(history.redo()?.gpioConfig).toEqual(configuredState.gpioConfig);
  });

  it('round-trips settings through share links and omits the key when empty', () => {
    const decoded = decodeWorkspaceState(encodeWorkspaceState(configuredState));
    expect(decoded.ok).toBe(true);
    if (decoded.ok) expect(decoded.state).toEqual(configuredState);

    expect(decodeRawPayload(encodeWorkspaceState(configuredState))).toHaveProperty('g');
    expect(decodeRawPayload(encodeWorkspaceState(baseState))).not.toHaveProperty('g');
  });

  it('rejects invalid electrical values in share links', () => {
    const json = JSON.stringify({ v: 2, m: chip.id, g: { '15': ['High', 'BiPolar', 'Up', 'Low'] } });
    const encoded = Buffer.from(deflateSync(strToU8(json), { level: 9 })).toString('base64url');
    const decoded = decodeWorkspaceState(encoded);
    expect(decoded.ok).toBe(true);
    if (decoded.ok) expect(decoded.state.gpioConfig).toBeUndefined();
  });

  it('round-trips settings through version-2 project files with sorted keys', () => {
    const text = exportPinoutJson(configuredState);
    const doc = JSON.parse(text) as Record<string, unknown>;
    expect(doc.version).toBe(2);
    expect(Object.keys(doc.gpioConfig as object)).toEqual(['15']);
    expect(Object.keys((doc.gpioConfig as Record<string, object>)['15'])).toEqual([
      'outputLevel',
      'drive',
      'pull',
      'speed',
    ]);
    const parsed = parsePinoutJson(text);
    expect(parsed.ok).toBe(true);
    if (parsed.ok) expect(parsed.state).toEqual(configuredState);

    const plain = parsePinoutJson(exportPinoutJson(baseState));
    expect(plain.ok).toBe(true);
    if (plain.ok) expect(plain.state.gpioConfig).toBeUndefined();
    expect(exportPinoutJson(baseState)).not.toContain('gpioConfig');
  });

  it('still rejects version-1 and version-3 payloads', () => {
    const v1 = JSON.stringify({ ...JSON.parse(exportPinoutJson(configuredState)), version: 1 });
    const v3 = JSON.stringify({ ...JSON.parse(exportPinoutJson(configuredState)), version: 3 });
    expect(parsePinoutJson(v1).ok).toBe(false);
    expect(parsePinoutJson(v3).ok).toBe(false);

    const v1Link = Buffer.from(deflateSync(strToU8(JSON.stringify({ v: 1, m: chip.id })), { level: 9 })).toString('base64url');
    const v3Link = Buffer.from(deflateSync(strToU8(JSON.stringify({ v: 3, m: chip.id })), { level: 9 })).toString('base64url');
    expect(decodeWorkspaceState(v1Link).ok).toBe(false);
    expect(decodeWorkspaceState(v3Link).ok).toBe(false);
  });
});

describe('GPIO electrical settings in workspace store', () => {
  it('commits settings through history and persists them in recent sessions', async () => {
    vi.resetModules();
    const { workspaceStore } = await import('../src/state/workspace.svelte.ts');
    const { catalogStore } = await import('../src/state/catalog.svelte.ts');
    catalogStore.primeChip(chip);
    await workspaceStore.openMcu(chip.id);
    workspaceStore.assignPin('15', { peripheral: 'SPI1', signal: 'SCK', af: 5 });

    workspaceStore.setGpioConfig('15', config);
    expect(workspaceStore.state.gpioConfig).toEqual({ '15': config });
    expect(workspaceStore.recentSessions[0].state.gpioConfig).toEqual({ '15': config });
    expect(workspaceStore.canUndo).toBe(true);

    workspaceStore.undo();
    expect(workspaceStore.state.gpioConfig).toBeUndefined();
    workspaceStore.redo();
    expect(workspaceStore.state.gpioConfig).toEqual({ '15': config });

    workspaceStore.setGpioConfig('15', null);
    expect(workspaceStore.state.gpioConfig).toBeUndefined();
  });

  it('serializes settings into localStorage sessions', async () => {
    const storage = new Map<string, string>();
    vi.stubGlobal('window', {
      localStorage: {
        getItem: (key: string) => storage.get(key) ?? null,
        setItem: (key: string, value: string) => storage.set(key, value),
      },
    });
    vi.resetModules();
    const { workspaceStore } = await import('../src/state/workspace.svelte.ts');
    const { catalogStore } = await import('../src/state/catalog.svelte.ts');
    catalogStore.primeChip(chip);
    await workspaceStore.openMcu(chip.id);
    workspaceStore.setGpioConfig('15', config);
    const sessions = JSON.parse(storage.get('pincraft:recent_sessions_v1') ?? '[]') as Array<{
      state: WorkspaceState;
    }>;
    expect(sessions[0].state.gpioConfig).toEqual({ '15': config });
    vi.unstubAllGlobals();
  });
});

describe('GPIO electrical settings in exporters', () => {
  it('keeps default STM32 Rust and C output byte-for-byte unchanged', () => {
    expect(exportEmbassyRust(chip, baseState)).toBe(BASELINE_RUST);
    expect(exportCHeader(chip, baseState)).toBe(BASELINE_C);
    expect(exportEmbassyRust(chip, baseState)).not.toContain('embedded-hal GPIO config');
    expect(exportCHeader(chip, baseState)).not.toContain('_LEVEL');
  });

  it('emits embedded-HAL-style Rust comments only for configured pins', () => {
    const rust = exportEmbassyRust(chip, configuredState);
    expect(rust).toContain(
      '// embedded-hal GPIO config: level=High, drive=OpenDrain, pull=Down, speed=VeryHigh',
    );
    expect(exportEmbassyRust(chip, { ...baseState, gpioConfig: {} })).toBe(BASELINE_RUST);
  });

  it('emits per-pin C macros with fixed value tokens', () => {
    const header = exportCHeader(chip, configuredState);
    expect(header).toContain('#define SPI1_SCK_LEVEL GPIO_LEVEL_HIGH');
    expect(header).toContain('#define SPI1_SCK_DRIVE GPIO_DRIVE_OPEN_DRAIN');
    expect(header).toContain('#define SPI1_SCK_PULL GPIO_PULL_DOWN');
    expect(header).toContain('#define SPI1_SCK_SPEED GPIO_SPEED_VERY_HIGH');
    expect(exportCHeader(chip, { ...baseState, gpioConfig: {} })).toBe(BASELINE_C);
  });

  it('appends four CSV columns with empty cells for unconfigured pins', () => {
    const lines = exportCsv(chip, configuredState).trim().split('\n');
    expect(lines[0]).toBe(
      'Vendor,Position,Pin,Type,Peripheral,Signal,Mux,Resource,Label,Locked,Level,Drive,Pull,Speed',
    );
    expect(lines[1]).toBe('stm32,15,PA5,io,SPI1,SCK,AF5,,,false,High,OpenDrain,Down,VeryHigh');

    const plain = exportCsv(chip, baseState, true).trim().split('\n');
    expect(plain[1]).toBe('stm32,1,VBAT,power,,,,,,false,,,,');
    expect(plain[2]).toBe('stm32,15,PA5,io,SPI1,SCK,AF5,,,false,,,,');
  });

  it('inherits settings in the JSON project exporter', () => {
    const parsed = parsePinoutJson(exportPinoutJson(configuredState));
    expect(parsed.ok).toBe(true);
    if (parsed.ok) expect(parsed.state.gpioConfig).toEqual({ '15': config });
  });
});
